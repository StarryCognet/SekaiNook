/**
 * 动效常量：底部 Tab 高光「弹到位」用的弹簧曲线。
 *
 * CSS 的 cubic-bezier 只能过冲一次（想多弹几次得堆关键帧），所以这里用 CSS `linear()`
 * 把一条真实的阻尼弹簧采样成 36 个点：y(t) = 1 - e^(-λt)·(cos(ωt) + (λ/ω)·sin(ωt))。
 * 弹几次、每次多大，全由阻尼比 λ/ω 决定；λ 越大衰减越快、ω 越大摆得越快。
 *
 * **过冲的比例基本恒定（18% → 15%），所以位移越短、甩出去的绝对距离越小，越短幅度越小：**
 *
 * | 跨度 | 首峰过冲 | 甩出去多远（约） | 时长 | 余震 |
 * | --- | --- | --- | --- | --- |
 * | 跨 1 格 | 18% | 12px（几乎看不出） | 550ms | 0.6% |
 * | 跨 2 格 | 17% | 23px | 620ms | 0.5% → 0.0% |
 * | 跨 3 格 | 16% | 33px | 700ms | 0.4% → 0.0% |
 * | 跨 4 格 | 15% | 41px | 780ms | 0.3% → 0.0% |
 *
 * 注意这两件事是此消彼长的：过冲越小，余震衰减得越快（物理上跑不掉）——
 * 所以短距那档基本只有一次过冲，长距那档才看得见两三次来回。要「短距离小幅度」，
 * 就得接受它不再明显回弹两三次；反之亦然。
 *
 * 系统开了「减少动态效果」时不要用它们，直接让元素瞬间到位。
 */
export interface SpringCurve {
  /** CSS 缓动：linear() 采样曲线 */
  easing: string;
  /** 时长（毫秒） */
  ms: number;
}


/**
 * 动效常量：底部 Tab 高光「弹到位」用的弹簧曲线。
 *
 * CSS 的 cubic-bezier 只能过冲一次（想多弹几次得堆关键帧），所以这里用 CSS `linear()`
 * 把一条真实的阻尼弹簧采样成 36 个点：y(t) = 1 - e^(-λt)·(cos(ωt) + (λ/ω)·sin(ωt))。
 * 弹几次、每次多大，全由阻尼比 λ/ω 决定；λ 越大衰减越快、ω 越大摆得越快。
 * 跨 4 格那档是例外：它把两个阻尼弹簧叠加起来用——
 * y(t) = 1 - [ w₁·e^(-λ₁t)(cos ω₁t + (λ₁/ω₁)·sin ω₁t) + w₂·e^(-λ₂t)(cos ω₂t + (λ₂/ω₂)·sin ω₂t) ]，
 * w₁ + w₂ = 1，所以 y(0) = 0、y'(0) = 0，起步不突兀——为的是要一条慢慢收的长尾巴。
 *
 * **前三档的过冲比例基本恒定（18% → 16%），所以位移越短、甩出去的绝对距离越小，越短幅度越小；
 * 跨 4 格那档刻意把首峰加大到 23%：**
 *
 * | 跨度 | 首峰过冲 | 甩出去多远（约） | 时长 | 余震 |
 * | --- | --- | --- | --- | --- |
 * | 跨 1 格 | 18% | 12px（几乎看不出） | 550ms | 0.6% |
 * | 跨 2 格 | 17% | 23px | 620ms | 0.5% → 0.0% |
 * | 跨 3 格 | 16% | 33px | 700ms | 0.4% → 0.0% |
 * | 跨 4 格 | 23% | 64px | 1150ms | 7.4% → 2.0% → 0.5% |
 *
 * 前三档是单弹簧，受物理约束：过冲越小，余震衰减得越快（跑不掉）——所以它们基本只有
 * 一次过冲，看不见第二、三次来回。跨 4 格那档为了要「尾巴慢慢收、来回摆两三次」，
 * 刻意放弃了单弹簧的物理一致性：改用一快一慢两个阻尼弹簧叠加，快弹簧顶首峰，
 * 慢弹簧撑住后面 7.4% → 2.0% → 0.5% 那几档余震。它是刻意的特效，
 * 不是同一条公式换参数换出来的；前三档仍保持「越短越轻、基本只过冲一次」。
 *
 * 系统开了「减少动态效果」时不要用它们，直接让元素瞬间到位。
 */
export interface SpringCurve {
  /** CSS 缓动：linear() 采样曲线 */
  easing: string;
  /** 时长（毫秒） */
  ms: number;
}


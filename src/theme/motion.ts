/** 按「跨了几格」取弹簧：0 格与 1 格同档，超过 4 格用最远那档 */
export function springForSteps(steps: number): SpringCurve {
  const index = Math.min(Math.max(Math.round(steps), 1), SPRING_BY_DISTANCE.length) - 1;
  return SPRING_BY_DISTANCE[index];
}

